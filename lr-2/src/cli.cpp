#include "cli.h"

#include <limits>
#include <stdexcept>

namespace cli {

std::uint64_t positive_number(const std::string& text) {
    if (text.empty()) {
        throw std::invalid_argument("Expected a positive integer");
    }

    std::uint64_t value = 0;

    for (char c : text) {
        if (c < '0' || c > '9') {
            throw std::invalid_argument("Expected decimal digits only");
        }

        const auto digit = static_cast<std::uint64_t>(c - '0');

        if (value > (std::numeric_limits<std::uint64_t>::max() - digit) / 10) {
            throw std::invalid_argument("Integer overflow");
        }

        value = value * 10 + digit;
    }

    if (value == 0) {
        throw std::invalid_argument("Value must be positive");
    }

    return value;
}

Arguments parse(int argc, char* argv[]) {
    Arguments args;

    if (argc == 2 && std::string(argv[1]) == "--help") {
        return args;
    }

    if (argc < 3) {
        throw std::invalid_argument("Expected command and database path; use --help");
    }

    const std::string command = argv[1];
    int expected = 3;

    if (command == "create") {
        args.command = Command::Create;
    } else if (command == "list") {
        args.command = Command::List;
    } else if (command == "add") {
        args.command = Command::Add;
        expected = 4;
    } else if (command == "find") {
        args.command = Command::Find;
        expected = 4;
    } else if (command == "generate") {
        args.command = Command::Generate;
        expected = 5;
    } else {
        throw std::invalid_argument("Unknown command; use --help");
    }

    if (argc != expected) {
        throw std::invalid_argument("Incorrect number of arguments; use --help");
    }

    args.path = argv[2];

    if (args.path.empty() || !codec::valid_ascii(args.path)) {
        throw std::invalid_argument("Expected a nonempty ASCII database path");
    }

    if (args.command == Command::Add) {
        args.text = argv[3];

        if (!codec::valid_ascii(args.text) || args.text.size() > codec::kMaxTextLength) {
            throw std::invalid_argument("Text must be ASCII, at most 1 MiB");
        }
    }

    if (args.command == Command::Find) {
        args.id = argv[3];

        if (!codec::valid_ascii(args.id) || args.id.size() != 36) {
            throw std::invalid_argument("UUID must contain 36 ASCII characters");
        }
    }

    if (args.command == Command::Generate) {
        args.count = positive_number(argv[3]);
        const auto max_length = positive_number(argv[4]);

        if (max_length > codec::kMaxTextLength) {
            throw std::invalid_argument("maxLen must be in 1..1048576 bytes");
        }

        args.max_length = static_cast<std::uint32_t>(max_length);

        // Windows file offsets are signed 64-bit integers.
        const auto max_file = static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max());

        if (args.count > (max_file - codec::kHeaderSize) / (codec::kRecordHeaderSize + max_length)) {
            throw std::invalid_argument("Generated file size would overflow a Windows file offset");
        }
    }

    return args;
}

std::string help() {
    return
        "Laboratory 2, variant 26: variable-length file database\n"
        "main.exe create <file>\n"
        "main.exe add <file> \"<text>\"\n"
        "main.exe list <file>\n"
        "main.exe find <file> <uuid>\n"
        "main.exe generate <file> <count> <maxLen>\n"
        "main.exe --help\n\n"
        "Paths and text must be ASCII. Quote arguments containing spaces.\n"
        "UUID is generated by Windows; find accepts 8-4-4-4-12 hex digits.\n"
        "count > 0; maxLen = 1..1048576 bytes. Generated text is ASCII.\n"
        "Text is at most 1 MiB; empty text is allowed.\n"
        "Windows command-line length limits also apply.\n"
        "create/generate never overwrite an existing file. Use separate lab data.\n"
        "Exit codes: 0 = success/not found, 1 = execution error, 2 = invalid arguments.\n\n"
        "add elapsed_ms: validation + write/flush; UUID/encoding/recheck excluded.\n"
        "find elapsed_ms: full scan/validation, even if a match is found early.\n"
        "list elapsed_ms excludes printing; file opening is excluded from all timings.\n";
}

} // namespace cli
